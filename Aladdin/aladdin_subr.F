      SUBROUTINE HIONN(PE, PCF, KNCF, PXS, KERMSG)
C
C     THIS IS A SUBROUTINE TO CALCULATE CROSS SECTIONS (cm[2])
C     VERSUS PROJECTILE ENERGY (eV).
C
C     PE = COLLISION ENERGY IN eV
C
C     PCF(1) = LOWER LIMIT OF THE VALIDITY OF THE ANALYTIC FIT.
C     PCF(2-9) = PARAMETERS FOR THE ANALYTIC FUNCTION.
C     PCF(10) = N
C
C     KERMSG = BLANK IF NO ERRORS
C
C     PXS = CROSS SECTION IN cm[2]
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PE, PCF, PXS
      DOUBLE PRECISION A1, A2, A3, A4, A5, A6, A7, A8, N, ERED
      DOUBLE PRECISION ARG1, ARG2, ZERO, C1, C2, DEXPR, E, ONE
C
      DIMENSION PCF(11)
      CHARACTER*(*) KERMSG
      DATA DEXPR/7.00D+02/
      DATA ZERO/0.00D+00/
      DATA ONE/1.00D+00/
C
      E = PE * 1.0D-03
      A1= PCF(2)
      A2= PCF(3)
      A3= PCF(4)
      A4= PCF(5)
      A5= PCF(6)
      A6= PCF(7)
      A7= PCF(8)
      A8= PCF(9)
      N = PCF(10)
      ERED =  ((3.0D0/N) ** 2 ) * E
C
      ARG1=-A2/ERED
      C1=ZERO
      IF (DABS(ARG1) .LT. DEXPR)
     1  C1=DEXP(ARG1) * DLOG(ONE+(A3*ERED))/ERED
C
      ARG2=-A5*ERED
      C2=ZERO
      IF (DABS(ARG2) .LT. DEXPR)
     1  C2=A4*DEXP(ARG2)/(ERED**A6 + A7*(ERED**A8))
C
      PXS = 1.0E-16 * A1 * ( C1 + C2 )
      PXS = PXS * (( N/3.0D0) ** 4)
C
      RETURN
      END
