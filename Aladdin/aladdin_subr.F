      SUBROUTINE ALMEWE(PTE, PCF, KNCF, PRATE, KERMSG)
C
C     GENERALIZED GAUNT FACTOR LINE EXCITATION CALCULATION
C
C     REFERENCE: R. MEWE, ASTRON. AND ASTROPHYS. 20, 215 (1972)
C
C
C     PTE = ELECTRON TEMPERATURE (KEV)
C
C     PCF(1) = PWVL = EXCITATION WAVELENGTH (ANGSTROMS)
C     PCF(2) = PEIJ = EXCITATION ENERGY (eV)
C            (IF PEIJ=0, ASSUME A RESONANCE LINE AND CALCULATE EIJ FROM PWVL)
C     PCF(3) = PFIJ = OSCILLATOR STRENGTH
C     PCF(4) = PBIJ = BRANCHING RATIO
C     PCF(5, 6, 7, 8) = PA, PB, PC, PD = COEFFICIENTS FOR GAUNT FACTOR FORMULA
C
C     KNCF = NUMBER OF COEFFICIENTS SUPPLIED IN PCF (MUST BE 8)
C     PRATE = LINE EXCITATION RATE COEFFICIENT (cm[3]/s)
C     KERMSG = ERROR MESSAGE, ' ' IS OK
C
C     WRITTEN BY R. A. HULSE
C
C======================================================================
C
      DOUBLE PRECISION PTE,PCF,PRATE
      DOUBLE PRECISION ZWVL, ZEIJ, ZFIJ, ZBIJ, ZA, ZB, ZC, ZD, ZY
      DOUBLE PRECISION ZGBAR, ZXCOEF
      DIMENSION PCF(8)
      CHARACTER*(*) KERMSG
C
      IF(PTE .LE. 0.0) THEN
        KERMSG = ' ALMEWE: TE .LE. 0'
        RETURN
      ELSE IF(KNCF .NE. 8) THEN
        KERMSG = ' ALMEWE: INCORRECT NUMBER OF COEFFICIENTS'
        RETURN
      ELSE
        KERMSG = ' '
      ENDIF
C
      ZWVL = PCF(1)
      ZEIJ = PCF(2)
      ZFIJ = PCF(3)
      ZBIJ = PCF(4)
      ZA = PCF(5)
      ZB = PCF(6)
      ZC = PCF(7)
      ZD = PCF(8)
C
      IF(ZEIJ .EQ. 0.0D0) ZEIJ = 12397.7D0 / ZWVL
C
      ZY = ZEIJ / (1000.0D0 * PTE)
C
C     GAUNT FACTOR
C
      ZGBAR = ZA + (ZB * ZY - ZC * ZY*ZY + ZD) *
     &    ( DLOG( (ZY+1.0D0)/ZY ) - 0.4D0 / ((1.0D0+ZY)**2)) + ZC * ZY
C
      ZXCOEF = 1.58D-05 * ZFIJ * ZGBAR * DEXP(-ZY)
     &           / (DSQRT(1000.0D0*PTE) * ZEIJ)
      PRATE = ZBIJ * ZXCOEF
C
      RETURN
      END
