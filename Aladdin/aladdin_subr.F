      SUBROUTINE JEION5(PE, PCF, KNCF, PXS, KERMSG)
C
C     THIS IS A SUBROUTINE TO CALCULATE A CROSS SECTION
C     IN CM[2] AS FUNCTION OF ELECTRON ENERGY IN EV.
C     FOR DETAILS SEE DOC=H-HE-PLASMA , USED FOR  REACTIONS
C     2.3.10, 2.3.11 (SEE DOC=H-HE-PLASMA.)
C
C     PCF IS THE COEFFICIENT DATA ARRAY, WHERE
C
C     PCF(1) =   NORMALISATION COEFFICIENT A
C
C     PCF(2)  =   PRINCIPAL QUANTUM NUMBER OF INITIAL STATE
C
C     PE = ELECTRON ENERGY (EV)
C
C     KERMSG = BLANK IF NO ERRORS
C
C     PXS = CROSS SECTION IN cm[2]
C
C     WRITTEN BY J. J. SMITH , IAEA ATOMIC AND MOLECULAR DATA UNIT
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PE, PCF, PXS
      INTEGER N
      DIMENSION PCF(2)
      CHARACTER*(*) KERMSG
      DATA RY/13.58/

      A=PCF(1)
      N=PCF(2)
      AN=N
C
      ETH = 4.0 *RY / (AN*AN)
      IF (PE .LT. ETH) THEN
        PXS  = 0.0
        RETURN
      ENDIF
C
      U = PE / ETH
      PXS  = A * ((RY/ETH)**2) * ((U-1.0)*(2.0+5.0*U))/(U**3)
C
      RETURN
C
      END
