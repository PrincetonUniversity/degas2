C#############################################################################
C
      SUBROUTINE ALCOMP(KHSL, KNHSL, KBASL, KNBASL,
     &                 KBNSL, KNBNSL, KMATCH)
C
C                 *************************************
C                 * ALADDIN STANDARD LABEL COMPARATOR *
C                 *************************************
C
C     THIS ROUTINE TAKES THE SUPPLIED SEARCH LABELS AND DETERMINES IF
C     THE PARSED ENTRY CURRENTLY IN COMMON / ALENT / MATCHES THIS
C     SEARCH CRITERION.  IN ORDER TO DO SO, THE HIERARCHICAL LABELS
C     MUST MATCH EXACTLY, EXCEPT THAT "*" AS A SEARCH LABEL ACTS AS A
C     WILDCARD, MATCHING ANY ENTRY LABEL IN THAT POSITION.  THE "**"
C     WILDCARD EXTENDS THE WILDCARD MATCH TO ANY NUMBER OF HIERARCHICAL
C     LABELS TO THE RIGHT OF THAT POSITION.  BOOLEAN .AND. SEARCH LABELS
C     MUST APPEAR IN THE ENTRY BOOLEAN FIELD FOR A MATCH TO BE SUCCESSFUL,
C     WHILE BOOLEAN .NOT. SEARCH LABELS MUST *NOT* APPEAR IN THE ENTRY
C     FOR A SUCCESFUL MATCH.
C
C     NOTE: LABEL COMPARISONS ARE UPPER-CASE/LOWER-CASE INSENSITIVE, USING
C           THE LOGICAL FUNCTION ALCIEQ INSTEAD OF THE .EQ. OPERATOR
C
C     KHSL   HIERARCHICAL SEARCH LABELS
C     KNHSL  NUMBER OF HIERARCHICAL SEARCH LABELS
C     KBASL  BOOLEAN .AND. SEARCH LABELS
C     KNBASL NUMBER OF BOOLEAN .AND. SEARCH LABELS
C     KBNSL  BOOLEAN .NOT. SEARCH LABELS
C     KNBNSL NUMBER OF BOOLEAN .NOT. SEARCH LABELS
C
C     KMATCH LOGICAL .TRUE./.FALSE. RETURN ON A SUCCESFUL MATCH
C
C------------------------------------------------------------------------------
C
C     NOTE: THIS IS AN ALADDIN STANDARD SUBROUTINE.  IT INTERFACES ONLY
C           THROUGH THE SUBROUTINE CALL PASSED VARIABLES AND COMMON / ALENT/.
C
C------------------------------------------------------------------------------
C
      CHARACTER*(*) KHSL(1), KBASL(1), KBNSL(1)
      LOGICAL KMATCH
      LOGICAL ALCIEQ
      EXTERNAL ALCIEQ
C
      INCLUDE 'ALPCOM.FOR'
C
C     INITIALIZE RETURN SUCCESS FLAG AS FALSE TO SIMPLIFY RETURNS
C
      KMATCH = .FALSE.
C
C     DO HIERARCHICAL SEARCH LABEL COMPARISON IF THERE
C     ARE ANY HSL'S
C
      IF(KNHSL .GT. 0) THEN
      DO 100 JHSL = 1, KNHSL
C
C     '*' IN A HIERARCHICAL SEARCH LABEL POSITION IS A WILD CARD MATCH
C
      IF(KHSL(JHSL) .EQ. '*') GO TO 100
C
C     '**' IN A HIERARCHICAL SEARCH LABEL POSITION IS WILD CARD MATCH
C     TO REST OF HIERACHICAL SEARCH LABEL FIELD; PROCEED TO BOOLEAN SEARCH
C
      IF(KHSL(JHSL) .EQ. '**') GO TO 150
C
C     IF THIS POSITION DOES NOT MATCH, OR DOES NOT EXIST IN ENTRY,
C     THEN THIS ENTRY IS REJECTED; GET NEXT ENTRY
C
      IF(JHSL .GT. NHL) RETURN
      IF( .NOT. ALCIEQ(KHSL(JHSL), HL(JHSL)) ) RETURN
C
  100 CONTINUE
      ENDIF
C
C     ALL HIERARCHICAL SEARCH LABELS MATCH; HOWEVER, WITHOUT A "**" WILDCARD,
C     REJECT ENTRY IF IT HAS MORE HL THAN IN SEARCH REQUEST
C
      IF(NHL .GT. KNHSL) RETURN
C
C     ENTRY HAS MATCHED HIERARCHICAL SEARCH LABELS; PROCEED TO BOOLEAN SEARCH
C     SEARCH FAILS IF THERE ARE .AND. SEARCH LABELS AND NO ENTRY BL'S
C     SEARCH AUTOMATICALLY SUCCEEDS IF THER ARE NO SEARCH LABELS INPUT
C
  150 IF(KNBASL .GT. 0 .AND. NBL .EQ. 0) RETURN
      IF(KNBASL .GT. 0 .AND. NBL .GT. 0) THEN
C
      DO 300 JBASL = 1, KNBASL
C
      DO 200 JBL = 1, NBL
      IF( ALCIEQ(KBASL(JBASL), BL(JBL)) ) GO TO 300
  200 CONTINUE
C
C     COMPLETING .AND. LOOP WITHOUT A MATCH MEANS THIS ENTRY IS REJECTED
C
      RETURN
  300 CONTINUE
      ENDIF
C
      IF(KNBNSL .GT. 0 .AND. NBL .GT. 0) THEN
      DO 500 JBNSL = 1, KNBNSL
C
      DO 400 JBL = 1, NBL
C
C     A MATCH WITH A BOOLEAN .NOT. LABEL CAUSES REJECTION OF THIS ENTRY
C
      IF( ALCIEQ(KBNSL(JBNSL), BL(JBL)) ) RETURN
  400 CONTINUE
C
  500 CONTINUE
      ENDIF
C
C     THIS ENTRY SATISFIES ALL SEARCH CRITERIA
C
      KMATCH = .TRUE.
C
      RETURN
      END
      LOGICAL FUNCTION ALCIEQ(KA, KB)
C
C     CASE-INSENSITIVE CHARACTER STRING .EQ. FUNCTION
C
C     NOTE: INPUT STRINGS KA AND KB ARE LEFT UNCHANGED BY THIS ROUTINE
C
      CHARACTER*(*) KA, KB
      CHARACTER*132 IUCA, IUCB
      CHARACTER*26 IUC, ILC
C
      IUC = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'
      ILC = 'abcdefghijklmnopqrstuvwxyz'
C
C     CONVERT BOTH STRINGS TO UPPER CASE AND THEN COMPARE
C
      IUCA = KA
      DO 100 J = 1, LEN(KA)
      IDX = INDEX(ILC, KA(J:J))
      IF(IDX .NE. 0) IUCA(J:J) = IUC(IDX:IDX)
  100 CONTINUE
C
      IUCB = KB
      DO 200 J = 1, LEN(KB)
      IDX = INDEX(ILC, KB(J:J))
      IF(IDX .NE. 0) IUCB(J:J) = IUC(IDX:IDX)
  200 CONTINUE
C
      ALCIEQ = IUCA .EQ. IUCB
C
      RETURN
      END
