      SUBROUTINE ALQMRK
C
C     ? IN COMMAND INDICATES STRING TO BE SEARCHED FOR FROM QUERY FILE
C
C
      INCLUDE 'ALCOM.FOR'
C
      CHARACTER*80 ILINE
      LOGICAL ALCIEQ
      EXTERNAL ALCIEQ
C
C     BLANK COMPRESS THE QUERY COMMAND
C
   50 IDX = INDEX(CMND, ' ')
      IF(IDX .NE. 0 .AND. CMND(IDX:) .NE. ' ') THEN
        CMND = CMND(:IDX-1) // CMND(IDX+1:)
        GO TO 50
      ENDIF
C
C     IF ? IS FIRST CHARACTER, SEND MESSAGE TO TERMINAL AND RETURN
C
      IF(CMND(1:1) .EQ. '?') THEN
        WRITE(LUTOUT,
     &  '(/'' USE {LABEL}? TO REFERENCE ALADDIN DICTIONARY'',
     &    /'' USE H OR C/R FOR ALADDIN COMMAND SUMMARY'')' )
      ENDIF
C
