      SUBROUTINE ACXGL2(PE, PCF, KNCF, PXS, KERMSG)
C
C     THIS IS A SUBROUTINE TO CALCULATE CROSS SECTION FOR
C     PROJECTILE ENERGY (eV/amu).
C
C     PE = PROJECTILE ENERGY (eV/amu)
C
C     KERMSG = BLANK IF NO ERRORS
C
C     PXS = CROSS SECTION IN cm[2]
C
C     PCF(1)  = PRINCIPAL QUANTUM NUMBER OF THE INITIAL STATE
C     PCF(2)  = CHARGE STATE OF THE PROJECTILE ION
C
C     WRITTEN BY J. J. SMITH , IAEA ATOMIC AND MOLECULAR DATA UNIT
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PE, PCF, PXS
      DOUBLE PRECISION N, Q, E, A, B, C, DEXPR, C1
      DIMENSION PCF(10)
      CHARACTER*(*) KERMSG
      DATA A/1.507D+05/
      DATA B/1.974D-05/
      DATA DEXPR/7.00D+02/
      N = PCF(1)
      Q = PCF(2)
C
C---  DETERMINE THE PROJECTILE ENERGY - IN SCALED UNITS
C
      E = PE*1.0D-03* (N*N) / DSQRT(Q)
      C =  - 2.0D0 * (E**3.5D0) * (1.0D0 + (B*(E**2.0D0))) / (3.0D0 * A)&
C
      C1=0.0D0
      IF (DABS(C) .LT. DEXPR) C1=DEXP(C)
C
      PXS = 7.04D-16 * A * Q* (N**4.0D0) * (1.0D0 - C1 )
     1            / ( E**3.5D0 * (1.0D0 + (B * (E**2.0D0) )))
C
      RETURN
C
      END
