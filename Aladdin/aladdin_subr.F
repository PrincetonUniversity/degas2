      CHARACTER*1 FSELF
      DOUBLE PRECISION RTABCF
      DIMENSION RTABCF (*)
C
      KERMSG = ' '
C
C       INITIALISE COEFFICIENT ARRAY ELEMENTS TO ZERO. ON ENTRY THEY
C       MAY BE NON-ZERO FROM LAST CALL
C
      DO 5 I=1,5
        RTABCF(I) = 0.0D0
  5   CONTINUE
C
C       READ AND CONVERT DATA IN INPUT TABLE HELD IN BUFFER EBUFF
C       AND LOOK FOR VALID ION AND TARGET COMBINATION MATCHING
C       VALUES IN CION AND CTARGT.
C
C       THE FIRST SIX LINES OF COEFFICIENT BLOCK DESCRIBE THE TABLE
C       FORMAT, THESE SHOULD NOT BE PROCESSED
C
      ILINE = LCFPTR + 6
