C
C     PCF(4)  = PARAMETER B
C
C     KNCF = NUMBER OF COEFFICIENTS SUPPLIED IN PCF (MUST BE 4)
C
C     KERMSG = BLANK IF NO ERRORS
C
C     PFIT = RATE COEFFICIENT IN cm[3]/s
C
C     EXTERNAL REFERENCE - EIEXP (WRITTEN BY J. J. SMITH ,
