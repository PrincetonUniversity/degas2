C
C     RTABCF(1) = ATOMIC NUMBER OF INCIDENT ION
C     RTABCF(2) = ATOMIC MASS OF INCIDENT ION
C     RTABCF(3) = ATOMIC NUMBER OF TARGET
C     RTABCF(4) = ATOMIC MASS OF TARGET
C     RTABCF(5) = SUBLIMATION ENERGY OF TARGET (EV)
C     RTABCF(6) = Q VALUE FOR TARGET
C
