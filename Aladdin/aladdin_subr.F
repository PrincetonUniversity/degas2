      DOUBLE PRECISION PE, PCF, PXS
      DOUBLE PRECISION N, C1
      DIMENSION PCF(10)
      CHARACTER*(*) KERMSG
      DATA DEXPR/7.00D+02/
      DATA ZERO/0.00D+00/
      N = PCF(5)
