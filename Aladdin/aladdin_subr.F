      SUBROUTINE FNRC(PT, PCF, KNCF, PFIT, KERMSG)
C
C     THIS IS A SUBROUTINE TO CALCULATE THE ELECTRON IMPACT
C     EXCITATION RATE COEFFICIENTS AS A FUNCTION OF THE ELECTRON
C     TEMPERATURE.
C
C     PT = ELECTRON TEMPERATURE IN eV
C
C     PCF IS THE COEFFICIENT DATA ARRAY, WHERE
C
C     PCF(1)  = ITYPE, INDEX FOR TYPE OF FIT, EITHER 1, 2 OR 3
C
C     PCF(2)  = Z, SPECTROSCOPIC SYMBOL OF TARGET ION
C
C     PCF(3)  = EXCITATION ENERGY , DELTA E
C
C     PCF(4)  = PARAMETER A
C
C     PCF(5)  = PARAMETER B
C
C     PCF(6)  = PARAMETER C
C
C     KNCF = NUMBER OF COEFFICIENTS SUPPLIED IN PCF (MUST BE 6)
C
C     KERMSG = BLANK IF NO ERRORS
C
C     PFIT = RATE COEFFICIENT IN cm[3]/s
C
C     EXTERNAL REFERENCE - EIEXP (WRITTEN BY J. J. SMITH ,
C                             IAEA ATOMIC AND MOLECULAR DATA UNIT)
C
C     TAKEN FROM PREPRINT IGP-PR-87, A.V. BOROVSKY ET AL, MOSCOW,
C     INSTITUTE OF GENERAL PHYSICS, SOVIET ACADEMY OF SCIENCE, (1987)
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PT, PCF, PFIT
      DIMENSION PCF(6)
      CHARACTER*(*) KERMSG
C
      IF(PT.LE.0.0) THEN
        KERMSG = ' FNRC: TE .LE. 0'
        RETURN
      ELSE IF(KNCF .NE. 6) THEN
        KERMSG = ' FNRC: INCORRECT NUMBER OF COEFFICIENTS'
        RETURN
      ELSE
        KERMSG = ' '
      ENDIF
C
      ITYPE = PCF(1)
      Z = PCF(2)
      DE = PCF(3)
      CONST = 9.127E-8*DE/(DSQRT(PT)*Z**4)
      Y = DE*13.606/PT
C
      EI1 = EIEXP(Y)
      EI2 = 1.-Y*EI1
C
C---   RATE COEFFICIENT FOR ALLOWED TRANSITION
C
      IF (ITYPE .EQ. 1) THEN
C
C---   RATE COEFFICIENT REPRESENTED BY POWER-LOG TYPE OF FIT
C
        PFIT = CONST*EXP(-Y)*(PCF(4)+(Y*PCF(5)+PCF(6))*EI1)
        IF (PFIT .LE. 0.0D0) GOTO 1
        RETURN
        ENDIF
C
C---   RATE COEFFICIENT FOR NONDIPOL TRANSITION
C
      IF (ITYPE .EQ. 2) THEN
C
C---   RATE COEFFICIENT REPRESENTED BY POWER TYPE OF FIT
C
        PFIT = CONST*EXP(-Y)*(PCF(4)+Y*(PCF(5)*EI1+PCF(6)*EI2))
        IF (PFIT .LE. 0.0D0) GOTO 1
        RETURN
        ENDIF
C
C---   RATE COEFFICIENT FOR SPIN-FLIP TRANSITION
C
      IF (ITYPE .EQ. 3) THEN
C
C---   RATE COEFFICIENT REPRESENTED BY POWER TYPE OF FIT
C
        EI3 = 0.5*(1.-Y*EI2)
        EI4 = (1.-Y*EI3)/3.0
        PFIT = CONST*EXP(-Y)*Y*(PCF(4)*EI2+PCF(5)*EI3+PCF(6)*EI4)
        IF (PFIT .LE. 0.0D0) GOTO 1
        RETURN
        ENDIF
C
   1   KERMSG =
     >  ' ERROR REACTION RATE IS NEGATIVE CHECK DATA AND TEMP. RANGE '
C
      RETURN
      END
