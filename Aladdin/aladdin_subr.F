      AN = PCF(1)
      ENION = RY/(AN * AN)
      BETA = ENION/PT
      POWER = -1.5
      PRATE = 9.56E-06 * (PT**POWER) * EXP (-BETA) /
     & (BETA**2.33 + (4.38* (BETA**1.72)) + 1.32*BETA)
C
      RETURN
      END
