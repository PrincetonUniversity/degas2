      SUBROUTINE ALD
C
C     DISPLAY ENTRY AND SEARCH QUANTITIES
C
C     D{FEL!CS} = DISPLAY ITEMS DENOTED BY COMBINATION OF TRAILING
C                  SYMBOLS
C
C     F = FILE NAMES
C     E = LITERAL DISPLAY OF ENTRY LINES
C     L = DISPLAY PARSED ENTRY LABELS
C     ! = DISPLAY ENTRY COMMENT LINES
C     C = DISPLAY PARSED ENTRY COEFFICIENTS
C         (IF STANDARD ENTRY ACCESS LABEL, DISPLAY AS REAL NUMBERS)
C         (IF NON-STANDARD ACCESS LABEL, DISPLAY AS LITERAL ENTRY LINES)
C     S = DISPLAY SEARCH LABELS
C     * = ALL THE ABOVE
C
C------------------------------------------------------------------------------
C
      INCLUDE 'ALPCOM.FOR'
C
      INCLUDE 'ALCOM.FOR'
C
      LOGICAL STAR
C
      IF(INDEX(CMND, '*') .NE. 0) THEN
        STAR = .TRUE.
      ELSE
        STAR = .FALSE.
      ENDIF
C
C     SUFFIX = F; DISPLAY INPUT AND OUTPUT FILE NAMES
C
      IF(INDEX(CMND, 'F') .NE. 0 .OR.
     &   INDEX(CMND, 'f') .NE. 0 .OR. STAR) THEN
        WRITE(LUTOUT, '(/''       INPUT DATA FILE: '', A)' ) DFNAME
        INQUIRE(LUOF, OPENED=OK)
        IF(.NOT.OK) OFNAME = '**NONE**'
        WRITE(LUTOUT, '( ''      OUTPUT DATA FILE: '', A)' ) OFNAME
        WRITE(LUTOUT, '( '' QUERY DICTIONARY FILE: '', A)' ) QFNAME
        WRITE(LUTOUT, '( ''   EV OUTPUT DATA FILE: '', A)' ) EFNAME
      ENDIF
C
C     SUFFIX = S; DISPLAY SEARCH LABELS
C
      IF(INDEX(CMND, 'S') .NE. 0 .OR.
     &   INDEX(CMND, 's') .NE. 0 .OR. STAR) THEN
        WRITE(LUTOUT, '(1X)')
C
        CALL ALLCON(NHSL,HSL,'HSL',.TRUE.)
C
        CALL ALLCON(NBASL,BASL,'BASL',.FALSE.)
C
        CALL ALLCON(NBNSL,BNSL,'BNSL',.FALSE.)
C
      ENDIF
C
C     ENTRY QUANTITY DISPLAYS, ONLY IF A VALID ENTRY EXISTS
C
      WRITE(LUTOUT, '(/, '' ENTRY SEQUENCE NUMBER = '', I8)' ) LESEQN
      IF(LESEQN .EQ. 0) THEN
        WRITE(LUTOUT, '(/, '' NO ENTRY CURRENTLY READ IN'')' )
        RETURN
      ENDIF
C
C     SUFFIX = E; DISPLAY LITERAL ENTRY LINES
C
      IF(INDEX(CMND, 'E') .NE. 0 .OR.
     &   INDEX(CMND, 'e') .NE. 0 .OR. STAR) THEN
        WRITE(LUTOUT, '(1X)')
        DO 50 JLN = 1, NELN
        INCH = 70
        IF(EBUFF(JLN)(INCH+1:) .NE. ' ') INCH = LEN(EBUFF(JLN))
        WRITE(LUTOUT, '(1X,I3,''['',A,'']'')') JLN, EBUFF(JLN)(1:INCH)
   50   CONTINUE
      ENDIF
C
C     SUFFIX = L; DISPLAY PARSED ENTRY LABELS
C
      IF(INDEX(CMND, 'L') .NE. 0 .OR.
     &   INDEX(CMND, 'l') .NE. 0 .OR. STAR) THEN
        WRITE(LUTOUT, '(1X)')
C
        CALL ALLCON(NHL,HL,'HL',.TRUE.)
C
        CALL ALLCON(NBL,BL,'BL',.FALSE.)
      ENDIF
C
C     SUFFIX = !; DISPLAY COMMENT LINES
C
      IF(INDEX(CMND, '!') .NE. 0 .OR. STAR) THEN
        IF(NCMLN .EQ. 0) THEN
          WRITE(LUTOUT, '(1X, ''NO COMMENT LINES IN THIS ENTRY'')' )
        ELSE
          WRITE(LUTOUT, '(1X,A)') (EBUFF(J), J = LCMPTR, LCMPTR+NCMLN-1)
        ENDIF
      ENDIF
C
C     SUFFIX = C; DISPLAY COEFFICIENTS
C
      IF(INDEX(CMND, 'C') .NE. 0 .OR.
     &   INDEX(CMND, 'c') .NE. 0 .OR. STAR) THEN
        WRITE(LUTOUT, '(1X)')
C
        IF(NCFLN .EQ. 0) THEN
          WRITE(LUTOUT, '(1X,''NO COEFFICIENT LINES IN THIS ENTRY'')')
C
        ELSE IF(BL(1) .NE. '$') THEN
          WRITE(LUTOUT, '('' *** NONSTANDARD ACCESS LABEL *** '')' )
          WRITE(LUTOUT,
     &          '('' COEFFICIENT LINES OUTPUT WITHOUT CONVERSION''/)')
          WRITE(LUTOUT, '(1X, A)')
     &                          (EBUFF(J), J = LCFPTR, LCFPTR+NCFLN-1)
C
        ELSE
          CALL ALRECF(CF, NCF, NCFMX, ERRMSG)
          IF (FEXTN) THEN
            WRITE(LUTOUT, 300) (JCF, CF(JCF), JCF = 1, NCF)
  300       FORMAT(1X,'CF:',I4,'[', 1PE13.6, ']',I4,'[', 1PE13.6, ']',
     &             I4,'[', 1PE13.6, ']',I4,'[', 1PE13.6, ']')
          ELSE
            WRITE(LUTOUT, 400) (JCF, CF(JCF), JCF = 1, NCF)
  400       FORMAT(1X,'CF:',I4,'[', 1PE21.14, ']',I4,'[', 1PE21.14, ']')
          ENDIF
C
        ENDIF
      ENDIF
C
      RETURN
      END
