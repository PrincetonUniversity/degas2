      SUBROUTINE ALG
C
C     G## = GO TO GIVEN ENTRY SEQUENCE NUMBER AND READ
C
C     N   = GO TO NEXT SEQUENTIAL ENTRY NUMBER AND READ
C
      INCLUDE 'ALPCOM.FOR'
C
      INCLUDE 'ALCOM.FOR'
C
C     GET DESIRED ENTRY NUMBER
C
      IF(CMND(2:) .EQ. ' ') GO TO 500
C
      READ(CMND(2:), '(BN,I10)', IOSTAT=IOS) IGSEQN
      IF(IOS .EQ. 0 .AND. IGSEQN .GT. 0) GO TO 10
C
      WRITE(LUTOUT, '(/'' ILLEGAL ENTRY NUMBER'')')
      RETURN
C
C     FOR ALN ENTRY JUST INCREMENT CURRENT SEQUENCE NUMBER
C
      ENTRY ALN
      IGSEQN = LESEQN + 1
C
C     RETURN IF WE ARE AT THIS SEQUENCE NUMBER ALREADY
C
   10 IF(IGSEQN .EQ. LESEQN) GO TO 500
C
      IF(IGSEQN .LT. LESEQN) THEN
        CALL ALR
      ENDIF
C
  100 CALL ALREAD(LUDF, LESEQN, EOF, ERRMSG)
C
      IF(EOF) THEN
         WRITE(LUTOUT,
     &   '(/'' END OF FILE AFTER ENTRY SEQUENCE NUMBER '',I6)')
     &    LESEQN
         RETURN
      ENDIF
C
      IF(ERRMSG .NE. ' ') THEN
        WRITE(LUTOUT, '('' ERROR: '', A)' ) ERRMSG
        RETURN
      ENDIF
C
      IF(LESEQN .NE. IGSEQN) GO TO 100
C
  500 WRITE(LUTOUT,
     &   '(/'' NOW AT ENTRY SEQUENCE NUMBER '', I6)' ) LESEQN
      RETURN
      END
