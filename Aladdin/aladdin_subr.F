C###################################################################
C
      SUBROUTINE JCX1(PE, PCF, KNCF, PXS, KERMSG)
C
C     THIS IS A SUBROUTINE TO CALCULATE A CHARGE TRANSFER CROSS SECTION
C     IN CM[2] AS FUNCTION OF IMPACT ENERGY IN EV.
C     FOR DETAILS SEE DOC=H-HE-PLASMA , USED FOR REACTION 3.1.12
C
C     PCF IS THE COEFFICIENT DATA ARRAY, WHERE
C
C     PCF(1)  = N,  PRINCIPAL QUANTUM NUMBER OF INITIAL STATE
C
C     PE = ELECTRON ENERGY (EV)
C
C     KERMSG = BLANK IF NO ERRORS
C
C     PXS = CROSS SECTION IN cm[2]
C
C     WRITTEN BY J. J. SMITH , IAEA ATOMIC AND MOLECULAR DATA UNIT
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PE, PCF, PXS
      INTEGER N
      DIMENSION PCF(2)
      CHARACTER*(*) KERMSG
      DATA RY/13.58/
C
      N = PCF(1)
      AN = N
      V=6.3246E-03 * SQRT(PE)
      ANV = AN * V
C
      PXS  = 1.584E-15 * (AN**4) / (1.0 + 0.8*(ANV**0.4) + 2.6*ANV )
C
      RETURN
C
      END
C
C###################################################################
C
      SUBROUTINE JCX2(PE, PCF, KNCF, PXS, KERMSG)
C
C     THIS IS A SUBROUTINE TO CALCULATE A CHARGE TRANSFER CROSS SECTION
C     IN CM[2] AS FUNCTION OF IMPACT ENERGY IN EV.
C
C     PCF IS THE COEFFICIENT DATA ARRAY, WHERE
C
C     PCF(1)  = N,  PRINCIPAL QUANTUM NUMBER OF INITIAL STATE
C
C     PCF(2)  = M,  PRINCIPAL QUANTUM NUMBER OF FINAL STATE
C
C     FOR CAPTURE INTO M = 2N-1 LEVELS THE CROSS SECTION CAN BE
C     DERIVED FROM THE CROSS SECTION FOR THE M = 2N CAPTURE.
C
C    - WARNING- .
C
C        THE COEFFICIENT ARRAY PCF IS UPDATED BY THIS ROUTINE TO
C     INCLUDE ENERGY INDEPENDENT CONSTANTS. THESE COEFFICIENTS CAN BE
C     USED IN SUBSEQUENT CALLS FOR THE SAME ENTRY. THE COEFFICEIENTS
C     ADDED ARE:
C
C     PCF(3) = ETH, THRESHOLD EXCITATION ENERGY FOR THE TRANSITION (eV)
C
C     PE = ELECTRON ENERGY (EV)
C
C     KERMSG = BLANK IF NO ERRORS
C
C     PXS = CROSS SECTION IN cm[2]
C
C     WRITTEN BY J. J. SMITH , IAEA ATOMIC AND MOLECULAR DATA UNIT
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PE, PCF, PXS
      INTEGER N, M
      DIMENSION PCF(3), RCOEFF(6)
      CHARACTER*(*) KERMSG
      DATA RY/13.58/
      DATA RCOEFF/0.75,0.8,0.85,0.9,0.95,0.98/
C
      N = PCF(1)
      M = PCF(2)
      AN = N
      AM = M
C
      KERMSG = ' '
      IF (KNCF .EQ. 2) THEN
C
C        FIRST CALL TO JCX2 4 DETERMINE ENERGY INDEPENDENT
C        PARAMETERS AND PLACE IN PCF FOR FURTHER USE
C
C        DETERMINE THE THRESHOLD ENERGY FROM THE ENERIES OF THE INITIAL
C        AND FINAL STATES
C
        IF (M .EQ. (2*N-1) ) THEN
          ETH = RY * (1.0/(AM*AM) - 1.0/((AM+1.0)**2))
        ELSE
          ETH = 0.0
        ENDIF
        PCF(3) = ETH
        KNCF = 3
C
      ELSE IF (KNCF .EQ. 3) THEN
          ETH  = PCF(3)
C
      ELSE
          KERMSG = ' INCORRECT NUMBER OF COEFFICIENTS PASSED TO JCX1'
          RETURN
      ENDIF
C
      IF (PE .LT. ETH) THEN
        PXS  = 0.0
        RETURN
      ENDIF
C
C----- THE CROSS SECTION FOR CAPTURE INTO M = 2N - 1 LEVELS CAN BE
C----- DERIVED FROM THE CROSS SECTION FOR CAPTURE INTO M = 2N LEVELS
C
      IF (M .EQ. (2*N-1) ) THEN
        IF (N .GT. 7) THEN
          CONST = 1.0
        ELSE
          CONST = RCOEFF(N-1)
        ENDIF
      ELSE
        CONST = 1.0
      ENDIF
C
      V=3.1623E-03 * SQRT(PE)
      ANV = AN * V
C
      PXS = 4.69E-16*CONST * (AN**4) / (1.0 + 0.8*(ANV**0.4) + 2.6*ANV )
C
      RETURN
C
      END
