        WRITE(LUTOUT, '('' LABEL "'', A, ''" TOO LONG'')' ) LABEL
        RETURN
      ENDIF
C
      IF(IFLAG .EQ. 1) GO TO 300
C
      IF(IFLAG .EQ. 0 .AND. LABEL .NE. '.') THEN
        NBASL = NBASL + 1
        BASL(NBASL) = LABEL
        GO TO 400
      ENDIF
C
      NBNSL = 0
  500 WRITE(LUTOUT, '('' BOOLEAN .NOT. SEARCH LABELS ?'')' )
      READ(LUTIN, '(A)') CMND
