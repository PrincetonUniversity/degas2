C
      SUBROUTINE ETABSQ(PE, PCF, KNCF, PYIELD, KERMSG)
C
C     THIS IS A SUBROUTINE TO CALCULATE THE YIELDS (ATOMS/ION) OF
C     ION-INDUCED SPUTTERING OF MONATOMIC SOLID
C
C     PE = COLLISION ENERGY IN eV
C
C     KERMSG = BLANK IF NO ERRORS
C
C     PYIELD = YIELD OF ATOMS/IONS PER INCIDENT ION
C
C     PCF(1) = ATOMIC NUMBER OF INCIDENT ION
C     PCF(2) = ATOMIC MASS OF INCIDENT ION
C     PCF(3) = ATOMIC NUMBER OF TARGET
C     PCF(4) = ATOMIC MASS OF TARGET
C     PCF(5) = SUBLIMATION ENERGY OF TARGET (EV)
C     PCF(6) = Q VALUE FOR TARGET
C
C     WRITTEN BY J. J. SMITH , IAEA ATOMIC AND MOLECULAR DATA UNIT
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PE, PCF, PYIELD
      DOUBLE PRECISION M1, Z1, M2, Z2, Q, ETA, SN, SE, K, ALPHA, US
      DOUBLE PRECISION Z123, Z223, SQRETA, ETH, GAMMA
C
      DIMENSION PCF(6)
      CHARACTER*(*) KERMSG
C
      Z1 = PCF(1)
      M1 = PCF(2)
      Z2 = PCF(3)
      M2 = PCF(4)
      US = PCF(5)
      Q = PCF(6)
C
      KERMSG = ' '
C
C---- DETERMINE THRESHOLD ENERGY
C
      GAMMA = 4.0D0 * M1 * M2 / ( (M1 + M2) **2 )
      IF (M1 .GE. M2) THEN
        ETH = (4.0D0/3.0D0)**6.0D0 * US/GAMMA
      ELSE
        ETH = (US/GAMMA)*((2.0D0*(M1+M2))/(M1+2.0D0* M2))**6.0D0
      ENDIF
      IF (PE .LT. ETH ) THEN
        KERMSG =
     &   ' INCIDENT ION ENERGY BELOW THRESHOLD FOR REACTION'
        RETURN
      ENDIF
C
C---- DETERMINE COMPONENTS OF EQUATION FOR YIELD
C
      Z123 = Z1**0.666666D0
      Z223 = Z2**0.666666D0
      ETA = 0.03255D0*M2*PE/(M1+M2)
      ETA = ETA/(Z1 * Z2 * DSQRT(Z123 + Z223))
      SQRETA= DSQRT(ETA)
C
      SN =  3.441D0 * SQRETA * DLOG (ETA + 2.718D0)/
     &  (1.0D0 + 6.355D0 * SQRETA + ETA * (-1.708D0 + 6.882D0 * SQRETA))
C
      SE =  SQRETA * 0.079D0 * ((M1+M2)**1.5D0) * Z123 * DSQRT(Z2)/
     &  (M1**1.5D0 * M2**0.5D0 * ((Z123 + Z223)**0.75D0))
C
      K = 8.478D0*Z1*Z2*M1/(DSQRT(Z123+Z223) * (M1+M2))
      ALPHA = 0.1D0+0.155D0*((M2/M1)**0.730D0) +
     &        0.001D0*((M2/M1)**1.5D0)
C
C       IF Q=0 SET Q=ALPHA
C
      IF (Q .EQ. 0.0D0) Q=ALPHA
C
C     FINALLY DETERMINE THE SPUTTERING YIELD
C
      PYIELD = 0.42D0 * ALPHA * Q * K * SN  *
     &         ((1.0D0 - DSQRT (ETH/PE))**2.8D0)  /
     &         (US * ( 1.0D0 + (0.35D0 * US * SE)))
      RETURN
C
      END
