C
      SUBROUTINE JEEXC6(PE, PCF, KNCF, PXS, KERMSG)
C
C     THIS IS A SUBROUTINE TO CALCULATE CROSS SECTIONS (cm[2])
C     VERSUS ENERGY (eV) FOR ELECTRON IMPACT EXCITATION.
C     THE FORMULA IS TAKEN FROM DOC=H-HE-PLASMA REACTION 2.3.8
C
C     PCF IS THE COEFFICIENT DATA ARRAY, WHERE
C
C     PCF(1)  =  N, PRINCIPAL QUANTUM NUMBER OF INITIAL STATE
C
C     PCF(2)  =  M,  PRINCIPAL QUANTUM NUMBER OF FINAL STATE
C
C    - WARNING- .
C
C        THE COEFFICIENT ARRAY PCF IS UPDATED BY THIS ROUTINE TO
C     INCLUDE ENERGY INDEPENDENT CONSTANTS. THESE COEFFICIENTS CAN BE
C     USED IN SUBSEQUENT CALLS FOR THE SAME ENTRY. THE COEFFICEIENTS
C     ADDED ARE:
C
C     PCF(3) = ETH, THRESHOLD EXCITATION ENERGY FOR THE TRANSITION (eV)
C
C     PCF(4) = XI, THE COEFFICIENT XI (SEE DOC=H-HE-PLAMA FOR DETAILS)
C
C     PCF(5) = FNM, THE OSCILLATOR STRENGTH AVERAGED OVER ANGULAR
C              MOMENTUM.
C
C     PE = ELECTRON ENERGY (EV)
C
C     KERMSG = BLANK IF NO ERRORS
C
C     PXS = CROSS SECTION IN cm[2]
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PE, PCF, PXS
C
      DIMENSION PCF(5)
      CHARACTER*(*) KERMSG
C
      DATA RY /1.358E+01/
C
      N = PCF(1)
      M = PCF(2)
      KERMSG = ' '
      IF (KNCF .EQ. 2) THEN
C
C        FIRST CALL TO JEEXC6 DETERMINE ENERGY INDEPENDENT
C        PARAMETERS AND PLACE IN PCF FOR FURTHER USE
C
C        DETERMINE THE THRESHOLD ENERGY FROM THE ENERIES OF THE INITIAL
C        AND FINAL STATES
C
          CALL HEIONEN(N, 0, 0, 1, EIONN, KERMSG)
          CALL HEIONEN(M, 0, 0, 1, EIONM, KERMSG)
          ETH = EIONN - EIONM
C
C        DETERMINE COEFFICIENT XI AND THE OSCILLATOR STRENGH FNM
C        THE OSSCILATOR STRENGTH IS DETERMINED FOR HYDROGENIC
C        TRANSISTIONS.
C
C     DETERMINE THE OSCILLATOR STRENGTH, FNM, FOR THE TRANSITION FROM
C     THE FORMULA OF JOHNSON
C
          CALL OSCSTH2(N, M, FNM)
          GAMMA = -0.7
          XI = 0.5* ( (FNM * RY /ETH)**GAMMA)
C

C        PLACE ENERGY INDEPENDENT PARAMETERS IN COEFFICIENT ARRAY AND
C        UPDATE KNCF
C
          PCF(3) = ETH
          PCF(4) = XI
          PCF(5) = FNM
          KNCF = 5
      ELSE IF (KNCF .EQ. 5) THEN
          ETH  = PCF(3)
          XI   = PCF(4)
          FNM  = PCF(5)
C
      ELSE
          KERMSG = ' INCORRECT NUMBER OF COEFFICIENTS PASSED TO JEEXC6'
          RETURN
      ENDIF
C
      IF (PE .LT. ETH) THEN
        PXS  = 0.0
        RETURN
      ENDIF
C
      U = PE / ETH
      CEXP =  - XI * (U + 1.0)
      IF (CEXP .LT. -20.0) THEN
        VEXP = 0.0
      ELSE
        VEXP = EXP(CEXP)
      ENDIF
      Y = (1.0 - VEXP) * LOG (U + 0.2 ) / U
      PXS  = 3.52E-16 * (RY/ETH) ** 2 * FNM * Y
C
      RETURN
C
      END
