C###################################################################
C
      SUBROUTINE EEXCH2(PE, PCF, KNCF, PXS, KERMSG)
C
C     THIS IS A SUBROUTINE TO CALCULATE CROSS SECTIONS (cm[2])
C     VERSUS ENERGY (eV) FOR ELECTRON IMPACT EXCITATION.
C
C     PE = COLLISION ENERGY IN eV
C
C     THIS EVALUATION FUNCTION REQUIRES THE PRINCIPAL QUANTUM NUMBERS
C     FOR THE INITIAL AND FINAL STATE TO BE PASSED IN THE COEFFICIENT
C     DATA ARRAY, SUCH THAT
C
C     PCF(1) = n, THE PRINCIPLE QUANTUM NUMBER OF THE INITIAL STATE
C     PCF(2) = m, THE PRINCIPLE QUANTUM NUMBER OF THE FINAL STATE
C
C    - WARNING- .
C
C        THE COEFFICIENT ARRAY PCF IS UPDATED BY THIS ROUTINE TO
C     INCLUDE ENERGY INDEPENDENT CONSTANTS. THESE COEFFICIENTS CAN BE
C     USED IN SUBSEQUENT CALLS FOR THE SAME ENTRY. THE COEFFICEIENTS
C     ADDED ARE, SEE DOC=H-HE-PLASMA FOR MEANING,
C
C     PCF(3) = THRESHOLD ENERGY FOR THE TRANSITION
C
C     PCF(4) = PARAMETER ANM
C
C     PCF(5) = PARAMETER BNM
C
C     PCF(6) = PARAMETER DELTA
C
C     PCF(7) = PARAMETER GAMMA
C
C     KERMSG = BLANK IF NO ERRORS
C
C     PXS = CROSS SECTION IN cm[2]
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PE, PCF, PXS
      INTEGER  N, M
C
      DIMENSION PCF(7)
      CHARACTER*(*) KERMSG

      DATA RY /1.358E+01/
C
      N = PCF(1)
      M = PCF(2)
      AN = N
      AM = M
      AN2 = AN * AN
C
      IF (M .LE. N) THEN
        KERMSG = 'ERROR  PRINCIPAL QUANTUM NUMBER m <= n '
        RETURN
      ENDIF
      IF (N .EQ. 1 .AND. M .EQ. 2) THEN
        KERMSG = 'ERROR TRANSITION NOT VALID FOR EEXCH2'
        RETURN
      ENDIF
      KERMSG = ' '
C
C        FIRST CALL TO EEXCH2 DETERMINE ENERGY INDEPENDENT
C        PARAMETERS AND PLACE IN PCF FOR FURTHER USE
C
      IF (KNCF .LT. 3) THEN
        ETH = RY * (1.0/AN2 - 1.0/(AM*AM))
C
C     DETERMINE THE OSCILLATOR STRENGTH, FNM, FOR THE TRANSITION FROM
C     THE FORMULA OF JOHNSON
C
        CALL OSCSTH2(N, M, FNM)
C
        ANM = 2.0 * RY * FNM / ETH
        BN = 1.4*LOG(AN)/AN - 0.7/AN - 0.51/AN2
     &         + 1.16/(AN2*AN)  - 0.55/(AN2*AN2)
C
        ENION = RY/AN2
C
        BNM = (4.0 * RY * RY / (AM **3.0 )) * ( 1.0/(ETH * ETH)
     &       +  (4.0 * ENION/(3.0 * (ETH ** 3.0))) +
     &         (BN * ENION * ENION / (ETH ** 4.0) ) )
C
        DELTA = EXP (-BNM/ANM) - 0.4 * ETH /RY
        S = ABS (AM - AN)
C
        GAMMA = RY * (8.0 + 23.0*((S/AN)**2.0)) /
     &    (8.0 + 1.1*AM*S + 0.8/(S*S) +
     &    0.4*AM*SQRT(AM/S)*ABS(S-1.0))
C
C        PLACE ENERGY INDEPENDENT PARAMETERS IN COEFFICIENT ARRAY AND
C        UPDATE KNCF
C
        PCF(3) = ETH
        PCF(4) = ANM
        PCF(5) = BNM
        PCF(6) = DELTA
        PCF(7) = GAMMA
        KNCF = 7
      ELSE IF (KNCF .EQ. 7) THEN
          ETH  = PCF(3)
          ANM  = PCF(4)
          BNM  = PCF(5)
          DELTA = PCF(6)
          GAMMA = PCF(7)
C
      ELSE
          KERMSG = ' INCORRECT NUMBER OF COEFFICIENTS PASSED TO EEXCH2'
          RETURN
      ENDIF
C
      IF (PE .LT. ETH) THEN
        PXS = 0.0
        RETURN
      ENDIF
C
C     DETERMINE THE VALUE OF THE CROSS SECTION  PXS
C
      PXS = 2.394E-15 * ( ANM*DLOG(PE/(2.0*RY) + DELTA) + BNM)
     &     / (PE + GAMMA)
C
      RETURN
      END
C
C###################################################################
C
      SUBROUTINE EIONH2(PE, PCF, KNCF, PXS, KERMSG)
C
C     THIS IS A SUBROUTINE TO CALCULATE CROSS SECTIONS (cm[2])
C     VERSUS ENERGY (eV) FOR ELECTRON IMPACT IONIZATION.
C
C     PE = COLLISION ENERGY IN eV
C
C     THIS EVALUATION FUNCTION REQUIRES THE PRINCIPAL QUANTUM NUMBER
C     FOR THE INITIAL STATE TO BE PASSED IN THE COEFFICIENT DATA
C     ARRAY, SUCH THAT
C
C     PCF(1) = n, THE PRINCIPLE QUANTUM NUMBER OF THE INITIAL STATE
C
C    - WARNING- .
C
C        THE COEFFICIENT ARRAY PCF IS UPDATED BY THIS ROUTINE TO
C     INCLUDE ENERGY INDEPENDENT CONSTANTS. THESE COEFFICIENTS CAN BE
C     USED IN SUBSEQUENT CALLS FOR THE SAME ENTRY.
C
C     PCF(2) = THRESHOLD ENERGY FOR THE TRANSITION
C
C     KERMSG = BLANK IF NO ERRORS
C
C     PXS = CROSS SECTION IN cm[2]
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PE, PCF, PXS
      DOUBLE PRECISION RY, N, ETH, ENION, XS1
C
      DIMENSION PCF(2)
      CHARACTER*(*) KERMSG

      DATA RY /1.358E+01/
C
      N = PCF(1)
      AN = N
C
C        FIRST CALL TO EIONH2 DETERMINE THRESHOLD ENERGY AND
C        PLACE IN PCF FOR FURTHER USE
C
      IF (KNCF .EQ. 1) THEN
         ETH = RY /(AN*AN)
         PCF(2) = ETH
        KNCF = 2
      ELSE IF (KNCF .EQ. 2) THEN
          ETH  = PCF(2)
      ELSE
          KERMSG = ' INCORRECT NUMBER OF COEFFICIENTS PASSED TO EIONH2'
          RETURN
      ENDIF
C
      IF(PE .GE. ETH) THEN
        KERMSG = ' '
      ELSE
        PXS = 0.0
        RETURN
      ENDIF
C
C
C     DETERMINE THE VALUE OF THE CROSS SECTION  PXS
C
      ENION = ETH
      XS1 = 5.0/(3.0*ENION) - 1.0/PE -
     &        (2.0*ENION)/(3.0*PE*PE)
      PXS = 6.51E-14 * XS1 / (PE + 3.25*ENION)
C
      RETURN
      END
