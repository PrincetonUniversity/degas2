      A1 = PCF(1)
      A2 = PCF(2)
      A3 = PCF(3)
      A4 = PCF(4)
      A5 = PCF(5)
      A6 = PCF(6)
C
C---  DETERMINE THE PROJECTILE ENERGY - PEK IN KeV/amu
C
      E = PE*1.0D-03
C
      PXS = 1.0D-16 * A1 * DLOG(A2/E + A6) /
     1      (1.0D0 + (A3*E) + (A4 * (E**3.5D0)) + (A5 * (E**5.4D0)))
C
      RETURN
C
      END
