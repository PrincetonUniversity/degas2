C###################################################################
C
      SUBROUTINE JDREC1(PT, PCF, KNCF, PRATE, KERMSG)
C
C     THIS IS A SUBROUTINE TO CALCULATE REACTION RATE COEFFICIENT
C     (CM[3]/S] VERSUS TEMPREATURE (EV) FOR DIELECTRONIC RECOMBINATION.
C     THE FORMULA IS TAKEN FROM DOC=H-HE-PLASMA REACTION 2.3.22
C
C     PCF(1)  = N0, PRINCIPAL QUANTUM NUMBER OF INITIAL STATE
C
C     PCF(2)  = N1,  PRINCIPAL QUANTUM NUMBER OF CAPTURED ELECTRON
C
C    - WARNING- .
C
C        THE COEFFICIENT ARRAY PCF IS UPDATED BY THIS ROUTINE TO
C     INCLUDE TEMPREATURE INDEPENDENT CONSTANTS. THESE COEFFICIENTS
C     CAN BE USED IN SUBSEQUENT CALLS FOR THE SAME ENTRY. THE
C     COEFFICIENTS ADDED ARE:
C
C     PCF(3) = COEFFICIENT BETAD
C
C     PT = TEMPERATURE IN eV
C
C     KERMSG = BLANK IF NO ERRORS
C
C     PRATE= REACTION RATE COEFFICIENT IN CM[3]/S
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PT, PCF, PRATE
      DIMENSION PCF(3)
      CHARACTER*(*) KERMSG

      DATA RY /1.358E+01/
C
      KERMSG = ' '
      IF (KNCF .EQ. 2) THEN
C
C        FIRST CALL TO JDREC1 DETERMINE TEMPERATURE INDEPENDENT
C        PARAMETERS AND PLACE IN PCF FOR FURTHER USE
C
         N0 = PCF(1)
         N1 = PCF(2)
         AN0 = N0
         AN1 = N1
         ETA = 1.0/ (AN0*AN0)   - 1.0/(AN1*AN1)
C
C        THE OSSCILATOR STRENGTH IS DETERMINED FOR HYDROGENIC
C        TRANSISTIONS.
C
C     DETERMINE THE OSCILLATOR STRENGTH, FNM, FOR THE TRANSITION FROM
C     THE FORMULA OF JOHNSON
C
          CALL OSCSTH2(N0, N1, FN0N1)

C
C        PLACE TEMPREATURE INDEPENDENT PARAMETERS IN COEFFICIENT ARRAY
C        AND UPDATE KNCF
C
          BETAD  = 480.0 * FN0N1 * SQRT(ETA/14.4) /
     &                  (1.0 + 0.21*ETA  + 0.6*(ETA*ETA))
          PCF(3) = BETAD
          KNCF = 3
      ELSE IF (KNCF .EQ. 3) THEN
          BETAD = PCF(3)
C
      ELSE
          KERMSG = ' INCORRECT NUMBER OF COEFFICIENTS PASSED TO JDREC1'
          RETURN
      ENDIF
C
      BETA0 = 4.0 * RY / PT
      CEXP =  - BETA0 * 0.99638
      IF (CEXP .LT. -20.0) THEN
        VEXP = 0.0
      ELSE
        VEXP = EXP(CEXP)
      ENDIF
      PRATE = 1.0E-13 * BETAD * (BETA0**1.5) * VEXP
C
      RETURN
      END
