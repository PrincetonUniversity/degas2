  10  READ(EBUFF(ILINE),
     &   '(BN,1X,A2,6X,F4.0,7X,F7.2,8X,F5.2,7X,F5.2,13X,A1)',
     &    END=100, IOSTAT=ICFERR) CATOM, ATMNO, ATMASS, SUBENG, Q, FSELF
C
C       IF NOT INTERNAL READ ERROR, LOOP BACK FOR NEXT COEFFICIENT
C       OTHERWISE, ERROR RETURN
C
      IF(ICFERR .EQ. 0) GO TO 20
