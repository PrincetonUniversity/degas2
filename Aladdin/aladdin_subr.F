C         (VALID IF FSELF ='*' )
C
         IF (CTARGT .EQ. CION .AND. FSELF .NE. '*')
     &     KERMSG =
     &      'THERE IS NO DATA FOR SELF SPUTTERING FOR TARGET IN TABLE'
         RETURN
       ENDIF
      ILINE = ILINE + 1
      GO TO 10
C
 100  KERMSG = 'END OF TABLE FILE NO ION/TARGET MATCH FOUND'
      END
