C
C     WRITTEN BY J. J. SMITH , IAEA ATOMIC AND MOLECULAR DATA UNIT
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PE, PCF, PXS
      DOUBLE PRECISION E, A1, A2, A3, A4, A5, A6
      DIMENSION PCF(6)
      CHARACTER*(*) KERMSG
C
C---  CHECK FOR ZERO ENERGY; FIT FUNCTION DIVERGES LOGARITHMICALLY THERE
C
      IF (PE.EQ.0.0D0) THEN
         PXS = 0.0D0
         KERMSG = ' CROSS SECTION DIVERGES AT 0 ENERGY'
         RETURN
      END IF
