      SUBROUTINE JEEXC7(PT, PCF, KNCF, PRATE, KERMSG)
C
C     THIS IS A SUBROUTINE TO CALCULATE REACTION RATE COEFFICIENT
C     (CM[3]/S] VERSUS TEMPREATURE (EV) FOR ELECTRON IMPACT EXCITATION.
C     THE FORMULA IS TAKEN FROM DOC=H-HE-PLASMA REACTION 2.3.18
C
C     PCF(1)  = N,  PRINCIPAL QUANTUM NUMBER OF INITIAL STATE
C
C     PCF(2)  = M,  PRINCIPAL QUANTUM NUMBER OF FINAL STATE
C
C    - WARNING- .
C
C        THE COEFFICIENT ARRAY PCF IS UPDATED BY THIS ROUTINE TO
C     INCLUDE TEMPREATURE INDEPENDENT CONSTANTS. THESE COEFFICIENTS
C     CAN BE USED IN SUBSEQUENT CALLS FOR THE SAME ENTRY. THE
C     COEFFICIENTS ADDED ARE:
C
C     PCF(3) = ETH, THRESHOLD EXCITATION ENERGY FOR THE TRANSITION (eV)
C
C     PCF(4) = FNM, THE OSCILLATOR STRENGTH AVERAGED OVER ANGULAR
C              MOMENTUM.
C
C     PT = TEMPERATURE IN eV
C
C     KERMSG = BLANK IF NO ERRORS
C
C     PRATE= REACTION RATE COEFFICIENT IN CM[3]/S
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PT, PCF, PRATE
      DIMENSION PCF(4)
      CHARACTER*(*) KERMSG

      DATA RY /1.358E+01/
C
      N = PCF(1)
      M = PCF(2)
      AN = N
      AM = M
      KERMSG = ' '
      IF (KNCF .EQ. 2) THEN
C
C        FIRST CALL TO JEEXC7 DETERMINE TEMPERATURE INDEPENDENT
C        PARAMETERS AND PLACE IN PCF FOR FURTHER USE
C
C        DETERMINE THE THRESHOLD ENERGY FROM THE ENERIES OF THE INITIAL
C        AND FINAL STATES
C
          ETH = 4.0 * RY   * (1.0/ (AN*AN)   - 1.0/(AM*AM))
C
C        THE OSSCILATOR STRENGTH IS DETERMINED FOR HYDROGENIC
C        TRANSISTIONS.
C
C     DETERMINE THE OSCILLATOR STRENGTH, FNM, FOR THE TRANSITION FROM
C     THE FORMULA OF JOHNSON
C
          CALL OSCSTH2(N, M, FNM)

C
C        PLACE ENERGY INDEPENDENT PARAMETERS IN COEFFICIENT ARRAY AND
C        UPDATE KNCF
C
          PCF(3) = ETH
          PCF(4) = FNM
          KNCF = 4
      ELSE IF (KNCF .EQ. 4) THEN
          ETH  = PCF(3)
          FNM  = PCF(4)
C
      ELSE
          KERMSG = ' INCORRECT NUMBER OF COEFFICIENTS PASSED TO JEEXC7'
          RETURN
      ENDIF
C
      CEXP =  - ETH/PT
      IF (CEXP .LT. -20.0) THEN
        VEXP = 0.0
      ELSE
        VEXP = EXP(CEXP)
      ENDIF
      PRATE = 1.16E-06 * (RY/ETH) * FNM * VEXP / DSQRT(PT)
C
      RETURN
      END
