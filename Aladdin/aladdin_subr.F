      SUBROUTINE JRREC3(PT, PCF, KNCF, PFIT, KERMSG)
C
C     THIS IS A SUBROUTINE TO CALCULATE A REACTION RATE COEFFICIENT
C     IN CM[3]/S AS FUNCTION OF ELECTRON TEMPREATURE IN EV FOR
C     RADIATIVE RECOMBINATION TO A FINAL STATE DEFINED IN TERMS OF ITS
C     PRINCIPAL QUANTUM NUMBER ALONE.
C
C     PCF IS THE COEFFICIENT DATA ARRAY, WHERE
C
C     PCF(1)  =   Z , THE ATOMIC NUMBER OF TARGET
C
C     PCF(2) =   Q, THE CHARGE STATE OF THE TARGET ION.
C
C     PCF(3) =   N, THE PRINCIPAL QUANTUM NUMBER OF THE FINAL STATE
C
C     PT = TEPREATURE (EV)
C
C     KERMSG = BLANK IF NO ERRORS
C
C     PFIT = REACTION RATE COEFFICIENT IN cm[3]/S
C
C     WRITTEN BY J. J. SMITH , IAEA ATOMIC AND MOLECULAR DATA UNIT
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PT, PCF, PFIT
      INTEGER SUMEN, N, Q
      DIMENSION PCF(3)
      CHARACTER*(*) KERMSG
      DATA RY/13.58/
C
      KERMSG = ' '
      Z=PCF(1)
      Q=PCF(2)
      N=PCF(3)
      AN = N
C
      IF (Z .EQ. 1) THEN
        ETH = RY /(AN*AN)
      ELSE IF (Z .EQ. 2 .AND. Q .EQ. 1) THEN
        SUMEN=1
        CALL HEIONEN(N , 0, 0, SUMEN, ETH, KERMSG)
      ELSE IF (Z .EQ. 2 .AND. Q .EQ. 2) THEN
        ETH = 4.0 * RY /(AN*AN)
      ELSE
          KERMSG= ' INVALID COMBINATION OF COEFFICIENTS IN JRREC3'
          RETURN
      ENDIF
      BETA = ETH/PT
C
      PFIT =  5.201 * 1.0E-14 * (BETA**1.5) * EXP(BETA) * EXINT(BETA)
      RETURN
C
      END
