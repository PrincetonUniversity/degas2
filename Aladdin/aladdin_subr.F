C###################################################################
C
      SUBROUTINE REFL3(PE, PCF, KNCF, REFL, KERMSG)
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PE, PCF, REFL
      DOUBLE PRECISION E
C
      DIMENSION PCF(9)
      CHARACTER*(*) KERMSG
C
      DATA E/2.7182818D0/
C
      REFL = PCF(1) * DLOG(PCF(2)*PE+E)/(1.0D0 + PCF(3)*(PE**PCF(4)) +
     1     PCF(5)*(PE**PCF(6))  )
      REFL = REFL * ( ( 1.0D0 -( ( PCF(7)/PE )**PCF(8)) )**PCF(9) )
C
      RETURN
      END
