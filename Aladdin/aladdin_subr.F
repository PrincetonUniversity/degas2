C
C     PCF(1) = PRINCIPAL QUANTUM NUMBER OF THE INITIAL STATE
C     PCF(2) = CHARGE STATE OF THE PROJECTILE ION
C
C     WRITTEN BY J. J. SMITH , IAEA ATOMIC AND MOLECULAR DATA UNIT
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PE, PCF, PXS
      DOUBLE PRECISION N, Q, CSQ, VSQ, QSQ, E, LAMDA, M2ION, BETA
      DOUBLE PRECISION GAMMA, C
      DIMENSION PCF(10)
      CHARACTER*(*) KERMSG
      DATA LAMDA/0.76D+00/
      DATA M2ION/0.283D+00/,BETA/4.04D0/,GAMMA/0.662D0/,C/137.0D0/
      N = PCF(1)
      Q = PCF(2)
C
C---  DETERMINE THE PROJECTILE ENERGY - IN SCALED UNITS
C
      E = PE*1.0D-03
      VSQ = (N*N)*E/25.0D0
      CSQ = C*C
      QSQ = Q*Q
C
      PXS = 3.52D-16 * DEXP(- LAMDA*Q/VSQ) * QSQ * (N**4) *
     1    ( M2ION * (DLOG(VSQ/(CSQ - VSQ)) - (VSQ/CSQ) )
     2    + BETA - GAMMA/VSQ ) / VSQ
C
      RETURN
C
      END
