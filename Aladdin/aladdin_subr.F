C
      SUBROUTINE ALKING(PET, PCF, KNCF, PFIT, KERMSG)
C
C     THIS IS AN IAEA SUBROUTINE TO CALCULATE THE REACTION RATE
C     COEFFICIENT (cm[3]/s) VERSUS ELECTRON TEMPREATURE (eV).
C
C     THESE FITS ARE VALID ONLY BETWEEN THE LIMITS TMIN AND TMAX,
C     WHICH ARE COEFFICIENTS PCF(2) AND PCF(3) IN THE ENTRY DATA FIELD
C     PCF(1) IS THE TRANSITION ENERGY (eV) FOR THE RECACTION
C
C     PET = MAXWELLIAN TEMPERATURE IN eV
C
C     KERMSG = BLANK IF NO ERRORS
C
C     PFIT = RATE COEFFICIENT IN cm[3]/s
C
C     WRITTEN BY J. J. SMITH , IAEA ATOMIC AND MOLECULAR DATA UNIT
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PET, PCF, PFIT
      DOUBLE PRECISION CONV, YTEMP, POWER1, POWER, TEN
      DOUBLE PRECISION EMIN, EMAX, TK, CONT
      DIMENSION PCF(12)
      CHARACTER*(*) KERMSG
      DATA CONV/1.16045D+04/
      DATA TEN/1.0D+01/
C
      EMIN = PCF(2)
      EMAX = PCF(3)
      IF(PET .GE. EMIN .AND. PET .LE. EMAX) THEN
        KERMSG = ' '
      ELSE
        KERMSG = 'OUTSIDE RANGE OF FIT IN ALKING'
        RETURN
      ENDIF
C
C     FORM THE ELECTRON TEMPREATURE IN DEGREES KELVIN
C
      TK = PET*CONV
      YTEMP = PCF(4)
C
C     GENERATE THE RATE COEFFICIENT FROM THE LOG POLYNOMIAL EXPRESSION
C
      POWER1 = DLOG10(TK)
      POWER = POWER1
      DO 10 I=5,KNCF
        CONT=PCF(I)*POWER
        YTEMP = YTEMP+CONT
        POWER = POWER * POWER1
  10  CONTINUE
      PFIT = TEN**YTEMP
  100 RETURN
C
      END
