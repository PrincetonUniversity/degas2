C
      FUNCTION EIEXP(X)
C
C    EIEXP=E1(X)*EXP(X)
C    HANDBOOK OF MATHEMATICAL FUNCTIONS, PAGE 231
C    BY M. ABRAMOWITZ AND I. A. STEGUN
C    (ROUTINE COPIED FROM IPPJ-AM-27, Y. ITIKAWA ET AL 1983)
      X2=X*X
      X3=X2*X
      X4=X3*X
      X5=X4*X
C
      IF (X.LE.1.0) THEN
        A0=-0.57721566
        A1=0.99999193
        A2=-0.24991055
        A3=0.05519968
        A4=-0.00976004
        A5=0.00107857
        EIEXP=(A0 +A1*X +A2*X2 +A3*X3 +A4*X4 +A5*X5 - LOG(X))*EXP(X)
C
      ELSE
        A1=8.5733287401
        A2=18.0590169730
        A3=8.6347608925
        A4=.2677737343
        B1=9.5733223454
        B2=25.6329561486
        B3=21.0996530827
        B4=3.9584969228
        EIEXP=(X4 +A1*X3+ A2*X2+ A3*X+ A4) /
     1       (X4 +B1*X3 +B2*X2 +B3*X+ B4)/X
      ENDIF
C
      RETURN
      END
