C###################################################################
C
      SUBROUTINE EEXCJN(PE, PCF, KNCF, PXS, KERMSG)
C
C     THIS IS A SUBROUTINE TO CALCULATE CROSS SECTIONS (cm[2])
C     VERSUS ELECTRON ENERGY (eV) FROM THE FORMULA OF JOHNSON,
C     ASTROPHYSICAL JOURNAL 174,227, (1972)
C
C     PE = COLLISION ENERGY IN eV
C
C     PCF(1) = N, THE PRINCIPAL QUANTUM NUNBER OF THE INITIAL STATE
C     PCF(2) = M, THE PRINCIPAL QUANTUM NUNBER OF THE FINAL STATE
C
C     KERMSG = BLANK IF NO ERRORS
C
C     PXS = CROSS SECTION IN cm[2]
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PE, PCF, PXS
      REAL NIN, NIN2, MIN, MIN2
C
      DIMENSION PCF(6)
      CHARACTER*(*) KERMSG
C
      DATA RY/13.6/
      DATA PI /3.14159/
C
      E = PE
      N =PCF(1)
      M =PCF(2)
      NIN = N
      MIN = M
      NIN2 = NIN*NIN
      MIN2 = MIN*MIN
C
C        FIRST CALL TO EEXCJN DETERMINE ENERGY INDEPENDENT
C        PARAMETERS AND PLACE IN PCF FOR FURTHER USE
C
      IF (KNCF .LT. 3) THEN
        ETH = RY * (1.0/NIN2 - 1.0/MIN2)
        EION = RY / NIN2
        X = ETH/EION
C
C     DETERMINE THE OSCILLATOR STRENGTH, FNM, FOR THE TRANSITION FROM
C     THE FORMULA OF JOHNSON
C
      CALL OSSCH(N, M, FNM)
C
      A=2.0*NIN2*FNM/X
      IF (N .EQ. 1) THEN
        BL = -0.603
      ELSE
        BL = (4.0 - 18.63/NIN + 36.24/NIN2  - 28.09/ (NIN*NIN2))/NIN
      ENDIF
      B = 4.0 * ((NIN2**2)/(MIN2*MIN*(X**2))) *
     1         ( 1.0 + (4.0/(3.0*X)) + BL/(X*X))
C
C     CALCULATE THE  COEFFICIENT R(N)
C
      IF (N .EQ. 1) THEN
        R = 0.45
      ELSE
        AEXP = -1.57
        R = 1.94 * NIN**AEXP
      ENDIF
        R = R * X
C
C        PLACE ENERGY INDEPENDENT PARAMETERS IN COEFFICIENT ARRAY AND
C        UPDATE KNCF
C
        PCF(3) = ETH
        PCF(4) = A
        PCF(5) = B
        PCF(6) = R
        KNCF = 6
      ELSE IF (KNCF .EQ. 6) THEN
          ETH  = PCF(3)
          A = PCF(4)
          B = PCF(5)
          R = PCF(6)
C
      ELSE
          KERMSG = ' INCORRECT NUMBER OF COEFFICIENTS PASSED TO EEXCJN'
          RETURN
      ENDIF
C
      IF (PE .LT. ETH) THEN
        PXS  = 0.0
        RETURN
      ENDIF
C
      U = E/ETH
      CEXP = - R * U
      IF (CEXP .LT. -30.0) THEN
        VEXP = 0.0
      ELSE
        VEXP = EXP(CEXP)
      ENDIF
C
      EION = RY / NIN2
      X = ETH/EION
      CXS2 = ( B - A * LOG (2.0*NIN2/X)) * (1.0 - 1.0/U)
C
      PXS =0.8797E-16 * 2.0 * NIN2 *  (1.0 - VEXP) *
     1   (A * (LOG (U) + 1.0/(2.0*U)) + CXS2 ) / (U*X)
C
      RETURN
      END
C
C###################################################################
C
      SUBROUTINE EIONJN(PE, PCF, KNCF, PXS, KERMSG)
C
C     THIS IS A SUBROUTINE TO CALCULATE CROSS SECTIONS (cm[2])
C     VERSUS ELECTRON ENERGY (eV) FROM THE FORMULA OF JOHNSON,
C     ASTROPHYSICAL JOURNAL 174,227, (1972)
C
C     PE = COLLISION ENERGY IN eV
C
C     PCF(1) = N, THE PRINCIPAL QUANTUM NUNBER OF THE INITILA STATE
C
C     KERMSG = BLANK IF NO ERRORS
C
C     PXS = CROSS SECTION IN cm[2]
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PE, PCF, PXS
      REAL NIN, NIN2
C
      DIMENSION PCF(5), G(3)
      CHARACTER*(*) KERMSG
C
      DATA RY/13.6/
      DATA PI /3.14159/
C
      E = PE
      N =PCF(1)
      NIN = N
      NIN2 = NIN*NIN
C
C        FIRST CALL TO EIONJN DETERMINE ENERGY INDEPENDENT
C        PARAMETERS AND PLACE IN PCF FOR FURTHER USE
C
      IF (KNCF .LT. 2) THEN
        ETH = RY /NIN2
C
C     DETERMINE THE GAUNT FACTOR COEFFICIENTS
C
        CALL GAUNTF(N, G(1), G(2), G(3))
C
C     CALCULATE THE BETHE COEFFICIENTS A(N) AND B(N)
C
      GSUM = 0.0
      DO 10 I=1,3
       GSUM =  GSUM +  (G(I)/(FLOAT(I-1) + 3.0))
  10  CONTINUE
      A = 32.0 * NIN * GSUM / (3.0 * SQRT(3.0) * PI)
C
      IF (N .EQ. 1) THEN
        BL = -0.603
      ELSE
        BL = (4.0 - 18.63/NIN + 36.24/NIN2  - 28.09/ (NIN*NIN2))/NIN
      ENDIF
      B = 2.0 * NIN2 * (5.0 + BL) / 3.0
C
C     CALCULATE THE  COEFFICIENT R(N)
C
      IF (N .EQ. 1) THEN
        R = 0.45
      ELSE
        AEXP = -1.57
        R = 1.94 * NIN**AEXP
      ENDIF
C
C        PLACE ENERGY INDEPENDENT PARAMETERS IN COEFFICIENT ARRAY AND
C        UPDATE KNCF
C
        PCF(2) = ETH
        PCF(3) = A
        PCF(4) = B
        PCF(5) = R
        KNCF = 5
      ELSE IF (KNCF .EQ. 5) THEN
          ETH  = PCF(2)
          A = PCF(3)
          B = PCF(4)
          R = PCF(5)
C
      ELSE
          KERMSG = ' INCORRECT NUMBER OF COEFFICIENTS PASSED TO EIONJN'
          RETURN
      ENDIF
C
      IF (PE .LT. ETH) THEN
        PXS  = 0.0
        RETURN
      ENDIF
C
      U = E/ETH
      CEXP = - R * U
      IF (CEXP .LT. -30.0) THEN
        VEXP = 0.0
      ELSE
        VEXP = EXP(CEXP)
      ENDIF
      CXS2 = ( B - A * LOG (2.0*NIN2)) * ((1.0 - 1.0/U)**2)
C
      PXS =0.8797E-16 * 2.0 * NIN2 *  (1.0 - VEXP) *
     1   (A * LOG (U) + CXS2 ) / U
C
      RETURN
      END
C
C###################################################################
C
      SUBROUTINE GAUNTF(N, G0, G1, G2)
C
C     THIS FUNCTION CALCULATES THE GAUNT FACTOR COEFFICIENTS AS
C     APPROXIMATED IN FORMULAE OF JOHNSON , L. C., ASTROPHYS. J. 174,
C     227, (1972).
C
C     N = THE PRINCIPLE QUANTUM NUMBER OF THE INITIAL STATE
C
      DATA PI /3.14159/
C
      AN = N
      N2= AN * AN
      IF (N. EQ. 1) THEN
        G0 = 1.1330
        G1 = -0.4059
        G2 = 0.07014
      ELSE IF(N .EQ. 2) THEN
        G0 = 1.0785
        G1 = -0.2319
        G2 = 0.02947
      ELSE
        G0 = 0.9935 + 0.2328/AN  -  0.1296/N2
        G1 = -(0.6282 - 0.5598/AN + 0.5299/N2)/AN
        G2 = (0.3887 - 1.181/AN + 1.47/N2)/N2
      ENDIF
C
      RETURN
      END
C
C###################################################################
C
      SUBROUTINE OSSCH(N, M, FNM)
C
C     THIS FUNCTION CALCULATES THE OSCILLATOR STRENGTH FNM FOR
C     HYDROGEN FROM THE FORMULAE OF JOHNSON , L. C., ASTROPHYS. J. 174,
C     227, (1972).
C
C     N = THE PRINCIPLE QUANTUM NUMBER OF THE INITIAL STATE
C     M = THE PRINCIPLE QUANTUM NUMBER OF THE FINAL STATE
C
      DATA PI /3.14159/
C
      AN=N
      AM=M
      AN2= AN * AN
      IF (N. EQ. 1) THEN
        G0 = 1.1330
        G1 = -0.4059
        G2 = 0.07014
      ELSE IF(N .EQ. 2) THEN
        G0 = 1.0785
        G1 = -0.2319
        G2 = 0.02947
      ELSE
        G0 = 0.9935 + 0.2328/AN  -  0.1296/AN2
        G1 = -(0.6282 - 0.5598/AN + 0.5299/AN2)/AN
        G2 = (0.3887 - 1.181/AN + 1.47/AN2)/AN2
      ENDIF
C
      X = 1.0 -((AN/AM)**2)
      GNX = G0 + G1/X + G2/(X*X)
      FNM = 32.0*AN*GNX /(3.0*SQRT(3.0)*PI*(AM**3.0)*(X**3.0))
C
      RETURN
      END
