      SUBROUTINE ALRECF(PCF, KNCF, KNCFMX, KERMSG)
C
C                  ****************************************
C                  * CONVERT COEFFICIENTS TO REAL NUMBERS *
C                  ****************************************
C
C     USING THE COEFFICIENT FIELD POINTERS IN COMMON / ALENT /,
C     PARSE THE COEFFICIENT LINES INTO REAL NUMBERS IN THE OUTPUT
C     ARRAY PCF.  KNCF RETURNS THE NUMBER OF COEFFICIENTS FOUND, WHILE
C     KNCFMX IS THE SUPPLIED DIMENSIONED LENGTH OF THE PCF ARRAY.
C     PROCESSING ERROR MESSAGES ARE RETURNED VIA KERMSG, WITH KERMSG = ' '
C     INDICATING NO ERRORS.
C
C                               **NOTE**
C
C     THE INDIVIDUAL COEFFICIENT VALUES ARE PARSED FROM THE COEFFICIENT
C     FIELD LINES AS BLANK-DELIMITED LABELS, USING THE ALXLBL ROUTINE.
C     THEREFORE, INDIVIDUAL DATA VALUES MUST BE BLANK DELIMITED (E.G.,
C     COMMAS ARE NOT VALID), AND MUST *NOT* CONTAIN ANY INTERNAL
C     BLANKS, OTHERWISE READ ERRORS WILL OCCUR !
C
C------------------------------------------------------------------------------
C
C     NOTE: THIS IS AN ALADDIN STANDARD SUBROUTINE.  IT INTERFACES USING
C           ONLY THE SUBROUTINE CALL PASSED VARIABLES AND COMMON / ALENT /.
C
C------------------------------------------------------------------------------
C
C     REV. 2/03/89 BY J.J.SMITH IAEA ATOMIC AND MOLECULAR DATA UNIT
C          PCF CHANGED FROM SINGLE TO DOUBLE PRECISION
C
C------------------------------------------------------------------------------
C
      DOUBLE PRECISION PCF(1)
      CHARACTER*(*) KERMSG
      CHARACTER*40 ILABEL
C
      INCLUDE 'ALPCOM.FOR'
C
      KERMSG = ' '
      KNCF = 0
      FEXTN = .TRUE.
C
      IF(NCFLN .EQ. 0) RETURN
C
      ILPTR = LCFPTR
      ICPTR = 1
C
  400 CALL ALXLBL(EBUFF, NELN, ILPTR, ICPTR, ILABEL, ILBLNC, IFLAG)
C
C     ACT ON LABEL SEARCH ERROR FLAGS
C
C     0 = OK
C     -1 = COEFFICIENT STRING TRUNCATED; ERROR RETURN
C     1 = END OF ENTRY REACHED PREMATURELY; ERROR RETURN
C
      IF(IFLAG .EQ. -1) THEN
        KERMSG = ' COEFFICIENT "'//ILABEL//'" TRUNCATED'
        RETURN
      ENDIF
C
      IF(IFLAG .EQ. 1) THEN
        IF(ILPTR .NE. NELN)
     &                 KERMSG = ' PREMATURE END OF COEFFICIENT FIELD'
        RETURN
      ENDIF
C
C     CONVERT THIS 'LABEL' TO A REAL NUMBER
C
      IF(KNCF .GE. KNCFMX) THEN
        KERMSG = ' COEFFICIENT ARRAY OVERFLOW'
        RETURN
      ENDIF
C
C     CHECK FOR THE LENGTH OF THE COEFFICIENT IF > 12 SET THE NUMBER
C     LENGTH FLAG TO TRUE.
C
      IF (ILBLNC .GT. 12) FEXTN =.FALSE.
C
      KNCF = KNCF + 1
      READ(ILABEL, '(BN,F20.0)', IOSTAT=ICFERR) PCF(KNCF)
C
C     IF NOT INTERNAL READ ERROR, LOOP BACK FOR NEXT COEFFICIENT
C     OTHERWISE, ERROR RETURN
C
      IF(ICFERR .EQ. 0) GO TO 400
C
      KERMSG = ' READ ERROR FOR COEFFICIENT "'//ILABEL//'"'
      RETURN
      END
