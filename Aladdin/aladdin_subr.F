C###################################################################
C
      SUBROUTINE HEXCLD(PE, PCF, KNCF, PXS, KERMSG)
C
C     SEMI-EMPIRICAL EXPRESSION FOR THE CROSS SECTION FOR EXCITATION
C     OF HYDROGEN ATOMS BY HEAVY PARTICLE IMPACT.
C
C     REFERENCE: J.G. LODGE, I.C. PERCIVAL, D. RICHARDS,
C                J. PHYS. B: AT. MOL. PHYS. 9, 239 (1976)
C
C     THIS IS AN IAEA SUBROUTINE TO CALCULATE THE EXCITATION CROSS
C     SECTION AS A FUNCTION OF THE INCIDENT PARTICLE ENERGY (eV/u), FOR
C     AN ELECTRON TRANSITION FROM AN INITIAL STATE, WITH A PRINCIPAL
C     QUANTUM NUMBER N, OF THE HYDROGEN ATOM TO SOME FINAL STATE WITH A
C     PRINCIPAL QUANTUM NUMBER M.
C
C     THE INITIAL AND FINAL STATE QUANTUM NUMBERS MUST BE PASSED IN THE
C     COEFFICIENT DATA ARRAY, AS,
C
C     PCF(1) = Q, THE CHARGE OF THE INCIDENT PROJECTILE
C     PCF(2) = N, PRINCIPAL QUANTUM NUMBER OF THE INITAL STATE OF THE
C              HYDROGEN ATOM.
C     PCF(3) = M, PRINCIPAL QUANTUM NUMBER OF THE FINAL STATE OF THE
C              HYDROGEN ATOM.
C
C     PE =  PROJECTILE ENERGY (eV/u)
C
C     KERMSG = BLANK IF NO ERRORS
C
C     PXS  = CROSS SECTION IN cm[2]
C
C     WRITTEN BY J. J. SMITH , IAEA ATOMIC AND MOLECULAR DATA UNIT
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PE, PCF, PXS, ERED
      DOUBLE PRECISION V2, V4, N, M, N2, M2, S, AD, AP, A, D, ALOGT
      DOUBLE PRECISION L, G, XM, XP, Y, CM, CP, H, ASEXP, AMULT, F, Q
      DOUBLE PRECISION QEXP, FACT
C
      DIMENSION PCF(3)
      CHARACTER*(*) KERMSG
      DATA QEXP/0.322D+00/
C
C     CALCULATE THE VELOCITY PARAMETERS FROM THE PROTON ENERGY IN
C     keV/u
C
      Q = PCF(1)
      N = PCF(2)
      M = PCF(3)
      N2 = N * N
      M2 = M * M
      ERED = PE/Q
      V2 = (ERED*1.0D-03)/25.0D0
      V4 = V2 * V2
C
      S = M - N
      AD = N2/M2
      AP = 2.0D0/3.0D0
C
      A = 8.0D0/(3.0D0*S)*((M/(S*N))**3)
      A = A * (0.184D0 -(0.04D0/(S**AP)))
C
      D = DEXP(-1.0D0/(N*M*V4))
C
      ALOGT = (1.0D0 + (0.530D0*N*V4*(M-(2.0D0/M)))) /
     &        (1.0D0 + 0.40D0*V2)
      L = DLOG(ALOGT)
C
      G = 0.5D0*((V2*N2/(M-(1.0D0/M)))**3)
C
      XM = 2.0D0/(V2*N2*(DSQRT(2.0D0 - AD)-1.0D0))
      XP = 2.0D0/(V2*N2*(DSQRT(2.0D0 - AD)+1.0D0))
      Y = 1.0D0/(1.0D0 -(D*DLOG(18.0D0*S)/(4.0D0*S)))
C
      CM = (XM*XM)*DLOG(1.0D0 + (2.0D0*XM/3.0D0)) / (2.0D0*Y + 1.5D0*XM)
      CP = (XP*XP)*DLOG(1.0D0 + (2.0D0*XP/3.0D0)) / (2.0D0*Y + 1.5D0*XP)
      H = CM-CP
C
      ASEXP = 1.0D0+ (2.0D0*S)
      AMULT = (1.0D0-(0.2D0*S/(N*M)))**ASEXP
      F = (1.0D0-0.3D0*S*D/(N*M))**ASEXP
C
      A = A * AMULT
C
      IF (Q .EQ. 1.0D0)  THEN
        FACT = 1.0D0
      ELSE IF (Q .EQ. 2.0D0) THEN
        FACT = 2.0D0
      ELSE
        FACT = 2.0D0 ** ( QEXP * (1 - DSQRT(2.0D0/Q) ) )
      ENDIF
      PXS = 0.88D-16 * FACT * (N2*N2/V2)*(A*D*L + (F*G*H))
C
      RETURN
      END
