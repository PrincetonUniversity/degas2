C
      SUBROUTINE HCX4(PE, PCF, KNCF, PXS, KERMSG)
C
C     THIS IS AN IAEA SUBROUTINE TO CALCULATE A CHARGE EXCHANGE
C     CROSS SECTION FOR A GIVEN PROJECTILE ENERGY (eV/amu).
C
C     PE = PROJECTILE ENERGY (eV/amu)
C
C     PCF IS THE COEFFICIENT DATA ARRAY, WHERE
C
C     PCF(1-11) = FITTING PARAMETERS.
C
C     KNCF   = NUMBER OF COEFFICIENTS IN ARRAY PCF
C
C     PXS = CROSS SECTION IN cm[2]
C
C     KERMSG = BLANK IF NO ERRORS
C
C     WRITTEN BY J. J. SMITH , IAEA ATOMIC AND MOLECULAR DATA UNIT
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PE, PCF, PXS
      DIMENSION PCF(11)
      CHARACTER*(*) KERMSG
C
C----   DEFINITION OF INTERNALLY USED VARAIBLES
C
      DOUBLE PRECISION ARG, C1, C2, E, ZERO, DEXPR
      DATA ZERO/0.0D+00/
      DATA DEXPR/7.0D+02/
C
C---  DETERMINE THE SCALED ENERGY (E) IN keV/amu
C
       E = PE*1.0D-03
C
C---  DETERMINE THE CROSS SECTION FROM THE THREE POSSIBLE CONTIBUTIONS
C
C ---  FIRST TERM DESCRIBES HIGH ENERGY BEHAVIOUR
C
      C1 = ZERO
      ARG=-PCF(2)/(E**PCF(8))
      IF ( DABS(ARG) . LT. DEXPR) C1= DEXP(ARG)/
     &  (1.0D0 + PCF(3)*(E**2.0D0) + (PCF(4)*(E**PCF(5)))
     &  + (PCF(6)*(E**PCF(7))))
C
      C2 = ZERO
      IF ( DABS(PCF(10)) .GT. ZERO ) THEN
        ARG=-PCF(10)*E
        IF ( DABS(ARG) . LT. DEXPR) C2= PCF(9)*DEXP(ARG)/(E**PCF(11))
      ENDIF
C
      PXS = 1.0D-16 * PCF(1) * ( C1 + C2 )
C
      RETURN
C
      END
