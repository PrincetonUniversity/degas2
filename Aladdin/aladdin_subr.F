C###################################################################
C
      SUBROUTINE JANRD(PT, PCF, KNCF, PFIT, KERMSG)
C
C     THIS IS A SUBROUTINE TO CALCULATE THE DOUBLE POLYNOMIAL
C     FITS FOR REACTION RATE COEFFICIENTS FOR COLLISIONS BETWEEN TWO
C     HEAVY PARTICLES FROM DOC=H-HE-PLASMA
C
C     THESE FITS ARE VALID ONLY BETWEEN THE TEMPERATURE LIMITS
C     WHICH ARE PARAMETERS PCF(1) AND PCF(2) AND THE ENERGY LIMITS
C     WHICH ARE PARAMETERS PCF(3) AND PCF(4) IN THE ENTRY DATA.
C     THE PARAMETERS PCF(5-85) ARE THE COEFICIENTS FOR THE FITTING
C     FORMULA. THE COEFFICIENTS ARE ARRANGED IN THE FOLLOWING ORDER
C
C       PCF(5) - PCF (13) = A(EINDEX,TINDEX)
C                            WITH EINDEX = 0  AND TINDEX FROM 0 TO 8
C       PCF(14) - PCF (22) = A(EINDEX,TINDEX)
C                            WITH EINDEX = 1  AND TINDEX FROM 0 TO 8
C        ETC. ETC.
C
C     PCF(86)  = E, THE ENERGY OF THE TARGET (IN EV)
C
C    - WARNING- .
C
C        THE COEFFICIENT ARRAY PCF IS UPDATED BY THIS ROUTINE TO
C     INCLUDE TEMPREATURE INDEPENDENT CONSTANTS. THESE COEFFICIENTS
C     CAN BE USED IN SUBSEQUENT CALLS FOR THE SAME ENTRY. THE
C     COEFFICIENTS ADDED ARE:
C
C     PCF(87-95)  = ENERGY DEPENDENT COEFFICIENTS (LN(E))**I  (I=0 TO 8)
C
C     PT = PLASMA TEMPREATURE IN eV
C
C     KERMSG = BLANK IF NO ERRORS
C
C     PFIT = REACTION RATE COEFFICIENT CM[3]/S
C
C     WRITTEN BY J. J. SMITH , IAEA ATOMIC AND MOLECULAR DATA UNIT
C
C------------------------------------------------------------------------
C
      DOUBLE PRECISION PT, PCF, PFIT
      DOUBLE PRECISION DELOG, TTERM, TLOG, SUMET, ETERM, SUMT, E
      DIMENSION PCF(95)
      DIMENSION TTERM (9)
      CHARACTER*(*) KERMSG
C
      IF(PT .GE. PCF(1) .AND. PT .LE. PCF(2)) THEN
        KERMSG = ' '
      ELSE
        KERMSG = 'OUTSIDE TEMPREATURE RANGE OF FIT IN JANRD'
        RETURN
      ENDIF
C
      IF (KNCF .EQ. 86)  THEN
        PCF(87) = 1.0D0
        E = PCF(86)
        DELOG = DLOG(E)
        PCF(88) = DELOG
        J=88
        DO 10 I=2,8
         J=J+1
         PCF(J) = PCF(J-1) * DELOG
  10    CONTINUE
        KNCF = 95
C
      ELSE IF (KNCF .NE. 95) THEN
          KERMSG = ' INCORRECT NUMBER OF COEFFICIENTS PASSED TO JANRD'
          RETURN
      ENDIF
C
C     CALCULATE DOUBLE NATUTRAL LOG POLYNOMIAL
C
      TTERM (1) = 1.0D0
      TLOG = DLOG(PT)
      TTERM (2) = TLOG
      DO 20 I=2,8
         J=I+1
         TTERM(J) = TTERM(J-1) * TLOG
  20    CONTINUE
C
      M=4
      SUMET = 0.0D0
      DO 30 I = 1, 9
        K =86 + I
        ETERM=PCF(K)
        SUMT = 0.0D0
C
C -------- SUM OVER A(I,J) * (LN(T) ** J) -> SUMT(I)
C
        DO 40 J=1,9
C
C     THE FIRST COEFFICIENT A(0,0) IS STORED IN PCF (5)
C
          M = M + 1
          SUMT = SUMT + PCF(M)*TTERM(J)
  40    CONTINUE
C
C -------- SUM OVER SUMT(I) -> SUMET
C
       SUMET =  SUMET + (SUMT * ETERM)

  30  CONTINUE
C
      PFIT = DEXP(SUMET)
      RETURN
C
      END
