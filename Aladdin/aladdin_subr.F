C
      DOUBLE PRECISION PT, PCF, PFIT
      DIMENSION PCF(2)
      CHARACTER*(*) KERMSG
C
      KERMSG = ' '
      ETH=PCF(1)
      A=PCF(2)
C
      BETA = ETH/PT
C
      PFIT = A * 1.0E-14 * (BETA**1.5) * EXP(BETA) * EXINT(BETA)
      RETURN
