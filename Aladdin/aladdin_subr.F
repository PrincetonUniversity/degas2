      SUBROUTINE ALL
C
C     L = DEFINE SEARCH LABELS
C
      INCLUDE 'ALCOM.FOR'
C
      WRITE(LUTOUT,
     &      '(/'' USE " ." AFTER LAST SEARCH LABEL IS ENTERED''/)' )
      NHSL = 0
  100 WRITE(LUTOUT,
     & '('' HIERARCHICAL SEARCH LABELS (* AND ** ARE WILDCARDS) ?'')')
      READ(LUTIN, '(A)') CMND
C
      ILPTR = 1
      ICPTR = 1
  200 CALL ALXLBL(CMND, 1, ILPTR, ICPTR, LABEL, NCHLBL, IFLAG)
C
      IF(IFLAG .EQ. -1) THEN
        WRITE(LUTOUT, '('' LABEL "'', A, ''" TOO LONG'')' ) LABEL
        RETURN
      ENDIF
C
      IF(IFLAG .EQ. 1) GO TO 100
C
      IF(IFLAG .EQ. 0 .AND. LABEL .NE. '.') THEN
        NHSL = NHSL + 1
        HSL(NHSL) = LABEL
        GO TO 200
      ENDIF
C
      NBASL = 0
  300 WRITE(LUTOUT, '('' BOOLEAN .AND. SEARCH LABELS ?'')' )
      READ(LUTIN, '(A)') CMND
C
      ILPTR = 1
      ICPTR = 1
  400 CALL ALXLBL(CMND, 1, ILPTR, ICPTR, LABEL, NCHLBL, IFLAG)
C
